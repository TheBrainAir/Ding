_ACCENT_HINTS = [("es", "ñ¿¡"), ("pt", "ãõ"), ("de", "ßäöü"), ("fr", "çœ"), ("tr", "ğış"), ("pl", "łśźżćń")]


def detect_language(text: str) -> str | None:
    text = text.strip()
    if not text:
        return None
    for code, pattern in _SCRIPTS:
        if re.search(pattern, text):
            return code
    if re.search(r"[Ѐ-ӿ]", text):
        if re.search(r"[іїєґІЇЄҐ]", text):
            return "uk"
        return "ru"

    words = re.findall(r"[\w']+", text.lower())
    if not words:
        return None
    scores = {lang: sum(1 for w in words if w in vocab) for lang, vocab in _LATIN_WORDS.items()}
    for lang, chars in _ACCENT_HINTS:
        if any(c in text.lower() for c in chars):
            scores[lang] += 2
    best = max(scores, key=lambda k: scores[k])
    if scores[best] == 0:
        return None
    return best
